"""Write the feature inventory of every prepared dataset as a LaTeX appendix (from audit.json; CPU, seconds).

For each feature family (NetFlow, CICFlowMeter) one table lists every model input feature, its type
(numeric / categorical / binary flag) and the datasets in which it is used; features that were removed
because they are constant in a dataset are marked. Also writes features.csv and prints the counts.

  python scripts/make_feature_table.py --datasets nf_unsw_v3 nf_ton_v3 nf_bot_v3 nf_cic2018_v3 cic2017_fixed \
      --out runs/feature_tables
Copy runs/feature_tables/tab_features.tex next to main.tex as mechanism/tab_features.tex.
"""
import argparse
import json
import sys
from pathlib import Path

import pandas as pd
import yaml

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from validaug.schema import TCP_FLAG_BITS  # noqa: E402

SHORT = {"nf_unsw_v3": "UNSW", "nf_ton_v3": "ToN", "nf_bot_v3": "BoT", "nf_cic2018_v3": "CIC18",
         "cic2017_fixed": "CIC17"}
FAMILY_TITLE = {"netflow": "NetFlow v3 datasets", "cicflowmeter": "CICFlowMeter dataset (corrected CIC-IDS2017)"}


def tt(name):
    return "\\texttt{" + name.replace("_", "\\_") + "}"


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--data-dir", default="data/processed")
    ap.add_argument("--datasets-cfg", default="configs/datasets.yaml")
    ap.add_argument("--datasets", nargs="+", required=True)
    ap.add_argument("--out", default="runs/feature_tables")
    a = ap.parse_args()
    out = Path(a.out); out.mkdir(parents=True, exist_ok=True)
    cfg = yaml.safe_load(open(a.datasets_cfg))["datasets"]
    rows, counts = [], []
    for ds in a.datasets:
        rep = json.load(open(Path(a.data_dir) / ds / "audit.json"))
        cat, bit = set(rep["categorical"]), set(rep["bit_features"])
        for f in rep["features"]:
            rows.append({"dataset": ds, "family": cfg[ds]["family"], "feature": f, "status": "used",
                         "type": "categorical" if f in cat else "binary flag" if f in bit else "numeric"})
        for f in rep.get("constant_dropped", []):
            is_bit = f.rsplit("_", 1)[-1] in TCP_FLAG_BITS and "flags" in f
            rows.append({"dataset": ds, "family": cfg[ds]["family"], "feature": f, "status": "constant",
                         "type": "binary flag" if is_bit else "numeric"})
        counts.append({"dataset": ds, "n_features": rep["n_features"], "numeric": len(rep["features"]) - len(cat) - len(bit),
                       "categorical": len(cat), "binary_flags": len(bit), "constant_dropped": len(rep.get("constant_dropped", []))})
    df = pd.DataFrame(rows)
    df.to_csv(out / "features.csv", index=False)
    C = pd.DataFrame(counts)
    C.to_csv(out / "feature_counts.csv", index=False)
    print(C.to_string(index=False))

    tex = ["% generated by scripts/make_feature_table.py -- do not edit"]
    for fam, g in df.groupby("family", sort=False):
        dss = [d for d in a.datasets if d in set(g.dataset)]
        order = {"numeric": 0, "categorical": 1, "binary flag": 2}
        first = g.drop_duplicates("feature").assign(o=lambda d: d["type"].map(order))
        # numeric and categorical in their original column order, flag bits last
        feats = list(first.sort_values("o", kind="stable")["feature"])
        ftype = dict(zip(first.feature, first["type"]))
        st = {(r.dataset, r.feature): r.status for r in g.itertuples()}
        n_used = {d: int(((g.dataset == d) & (g.status == "used")).sum()) for d in dss}
        tex += ["\\begin{longtable}{rll" + "c" * len(dss) + "}",
                "\\caption{Model input features of the %s. \\checkmark: used; c: removed because constant in that dataset; "
                "--: not present. Identifiers, addresses, source port, timestamps and labels are never used as features.}"
                "\\label{tab:features-%s}\\\\" % (FAMILY_TITLE.get(fam, fam), fam),
                "\\toprule", "\\# & Feature & Type & " + " & ".join(SHORT.get(d, d.replace("_", "\\_")) for d in dss) + " \\\\",
                "\\midrule", "\\endfirsthead", "\\toprule",
                "\\# & Feature & Type & " + " & ".join(SHORT.get(d, d.replace("_", "\\_")) for d in dss) + " \\\\",
                "\\midrule", "\\endhead", "\\bottomrule", "\\endfoot"]
        for i, f in enumerate(feats, 1):
            cells = [{"used": "\\checkmark", "constant": "c"}.get(st.get((d, f)), "--") for d in dss]
            tex.append("%d & %s & %s & %s \\\\" % (i, tt(f), ftype[f], " & ".join(cells)))
        tex += ["\\midrule", "\\multicolumn{3}{l}{Features used} & " + " & ".join(str(n_used[d]) for d in dss) + " \\\\",
                "\\end{longtable}", ""]
    (out / "tab_features.tex").write_text("\n".join(tex))
    print("written:", out / "tab_features.tex")


if __name__ == "__main__":
    main()
